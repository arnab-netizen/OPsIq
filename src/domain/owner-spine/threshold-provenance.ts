/**
 * Owner Intelligence — THRESHOLD PROVENANCE REGISTRY (pure metadata, no I/O).
 *
 * OpsIQ thresholds are NOT automatically scientific, statistical or industry-standard. Every consequential
 * threshold below carries exactly one provenance class stating where it honestly comes from. This module is
 * DOCUMENTATION AND GOVERNANCE ONLY:
 *
 *   - it is never imported by production scoring/diagnosis/decision code (a test enforces this), so it can never
 *     become the source production calculations read thresholds from;
 *   - the `value` fields RECORD the current production values; a governance test compares them with the real
 *     production exports, so any change to a registered value must be a deliberate, reviewed change here too;
 *   - it changes no threshold, formula, severity mapping, window, weight, ordering or output.
 *
 * Provenance vocabulary (primary classification, exactly one per record):
 *   EXTERNAL_STANDARD_VERIFIED  the exact value is supported by an authoritative external source (source, claim,
 *                               applicability and date/version REQUIRED). None qualifies today.
 *   EXTERNAL_GUIDANCE_ADAPTED   external guidance supports the direction/range but NOT the exact number.
 *   INDUSTRY_TEMPLATE           the value varies by an industry template defined in code. A template label is NOT
 *                               evidence the number is an industry standard.
 *   INTERNAL_PRODUCT_POLICY     a deliberate OpsIQ business/safety/product choice.
 *   INTERNAL_HEURISTIC          a deterministic engineering/product heuristic with no verified external origin.
 *   DERIVED_FROM_OTHER_RULE     mechanically derived from another registered threshold (`parentId`).
 *   LEGACY_OR_UNKNOWN           no defensible origin can be established in the repository. Not invented.
 *
 * See docs/opsiq/architecture/OWNER_THRESHOLD_PROVENANCE.md.
 */

