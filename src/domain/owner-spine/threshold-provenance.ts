interface GlobalArgs {
  id: string;
  domain: string;
  family: ThresholdFamily;
  metric: string;
  productionSource: string;
  value: number | string;
  unit: ThresholdUnit;
  comparison: ThresholdComparison;
  effect: string;
  provenance: ThresholdProvenanceClass;
  confidence?: ProvenanceConfidence;
  repoEvidence: string;
  ownerConsequence: string;
  ranking?: boolean;
  parentId?: string;
  status?: ThresholdReviewStatus;
  externalSources?: readonly ExternalSourceNote[];
}

/** A hand-curated record for a global / cross-cutting / rule-level threshold. */
function g(a: GlobalArgs): ThresholdRecord {
  return {
    id: a.id,
    domain: a.domain,
    family: a.family,
    metric: a.metric,
    productionSource: a.productionSource,
    value: a.value,
    unit: a.unit,
    comparison: a.comparison,
    effect: a.effect,
    provenance: a.provenance,
    provenanceConfidence: a.confidence ?? (a.provenance === "LEGACY_OR_UNKNOWN" ? "none" : "low"),
    repoEvidence: a.repoEvidence,
    externalSources: a.externalSources ?? NO_SOURCES,
    parentId: a.parentId,
    ownerConsequence: a.ownerConsequence,
    affectsRankingOrDecision: a.ranking ?? false,
    changeChangesNumericOutput: true,
    reviewStatus: a.status ?? "INVENTORIED_NOT_VALIDATED",
  };
}


