/** Records whose registered value is defined in code but never read by any production calculation. */
const UNREFERENCED_THRESHOLD_IDS: ReadonlySet<string> = new Set(["FIN.highOwnerWithdrawalPressurePct"]);

function applyOverrides(r: ThresholdRecord): ThresholdRecord {
  if (!UNREFERENCED_THRESHOLD_IDS.has(r.id)) return r;
  return {
    ...r,
    effect:
      "DEFINED BUT NOT READ: no finance rule, metric or recommendation references this field (verified by search of src/domain and src/services); it currently changes no behavior",
    provenance: "LEGACY_OR_UNKNOWN",
    provenanceConfidence: "none",
    repoEvidence: "Declared in FinanceThresholds and the generic defaults, never read. Cashflow has a same-named field that IS used (CASH.highOwnerWithdrawalPressurePct = 30).",
    ownerConsequence: "None today.",
    affectsRankingOrDecision: false,
    changeChangesNumericOutput: false,
    reviewStatus: "DEFINED_BUT_UNREFERENCED",
  };
}

/** The frozen, deterministic registry (declaration order). */
export const THRESHOLD_REGISTRY: readonly ThresholdRecord[] = Object.freeze(RAW_REGISTRY.map((r) => Object.freeze(applyOverrides(r))));

export function thresholdById(id: string): ThresholdRecord | undefined {
  return THRESHOLD_REGISTRY.find((r) => r.id === id);
}

/** Count of records per provenance class (all classes present, zero when empty). */
export function provenanceCounts(): Record<ThresholdProvenanceClass, number> {
  const counts = Object.fromEntries(THRESHOLD_PROVENANCE_CLASSES.map((c) => [c, 0])) as Record<ThresholdProvenanceClass, number>;
  for (const r of THRESHOLD_REGISTRY) counts[r.provenance] += 1;
  return counts;
}
