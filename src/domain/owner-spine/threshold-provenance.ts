export type ThresholdFamily = (typeof THRESHOLD_FAMILIES)[number];

export const THRESHOLD_COMPARISONS = ["below", "above", "at_or_above", "at_or_below", "older_than", "lookup", "table"] as const;
export type ThresholdComparison = (typeof THRESHOLD_COMPARISONS)[number];

export const THRESHOLD_UNITS = ["days", "months", "hours", "percent", "ratio", "points", "score", "confidence", "count", "lookup"] as const;
export type ThresholdUnit = (typeof THRESHOLD_UNITS)[number];

export const PROVENANCE_CONFIDENCES = ["none", "low", "medium", "high"] as const;
export type ProvenanceConfidence = (typeof PROVENANCE_CONFIDENCES)[number];

